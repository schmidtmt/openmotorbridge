#pragma once

#include <stdint.h>
#include "driver/gpio.h"

// =============================================================================
// OpenMotorBridge v10.0 - Front-Node Chip 2 (PCBA 05 U10) Hardware Configuration
// Controller: ESP32-C3FH4 (32-Bit RISC-V @ 160 MHz, 4MB In-Package Flash)
// Primary Role:
//   - USB 2.0 Client to Harley Boom! Box GTS / SkylineOS or Aftermarket Display
//   - COMM_20: WHIM Headset Presence & Pairing Emulation to unlock wired CarPlay
//   - COMM_19: USB Audio Class 1.0 (UAC) Bike Speaker Output (Stereo 48 kHz PCM)
//   - COMM_21: USB HID Consumer Control (Media Play/Pause, Next/Prev, Vol +/-)
//   - COMM_14/15: 921600 Baud Inter-Chip Control Link with S31 (U1)
//   - COMM_16/17: Digital I2S Audio Bus (Slave) with S31 (U1)
// =============================================================================

#define FRONT_C3_FW_REV_MAJOR       10
#define FRONT_C3_FW_REV_MINOR       0

// --- 1. USB 2.0 Full-Speed Client PHY (To U8 TS3USB221 Multiplexer) ---
#define PIN_C3_USB_DM               GPIO_NUM_18 // Pad 12 (C3_USB_DM) -> U8 TS3USB221
#define PIN_C3_USB_DP               GPIO_NUM_19 // Pad 13 (C3_USB_DP) -> U8 TS3USB221

// --- 2. High-Speed Inter-Chip UART Link (S31 U1 <-> C3 U10) ---
#define PIN_C3_UART_RX              GPIO_NUM_20 // Pad 20 (C3_UART_TX from S31 Pad 14 GPIO34)
#define PIN_C3_UART_TX              GPIO_NUM_21 // Pad 21 (C3_UART_RX to S31 Pad 13 GPIO33)
#define C3_INTERCHIP_UART_NUM       UART_NUM_0
#define C3_INTERCHIP_BAUDRATE       921600

// --- 3. Digital I2S Audio Bus (Slave Mode: Clocks generated by S31 U1) ---
#define PIN_C3_I2S_MCLK             GPIO_NUM_4  // Pad 18 (C3_I2S_MCLK)
#define PIN_C3_I2S_BCLK             GPIO_NUM_5  // Pad 19 (C3_I2S_BCLK)
#define PIN_C3_I2S_WS               GPIO_NUM_6  // Pad 20 (C3_I2S_WS)
#define PIN_C3_I2S_SDO              GPIO_NUM_7  // Pad 21 (C3_I2S_SDO - Audio Stream to Speakers)
#define PIN_C3_I2S_SDI              GPIO_NUM_8  // Pad 22 (C3_I2S_SDI - Mic In from Headunit)

// --- 4. Inter-Chip Packet Protocol Types (COMM_14 & COMM_15) ---
#define INTERCHIP_MAGIC             0xA5

enum InterchipPktType : uint8_t {
    INTERCHIP_CMD_AUDIO_ROUTE     = 0x01, // S31 -> C3: Routing mode (0=Headset Only, 1=Bike Speakers, 2=Dual)
    INTERCHIP_CMD_WHIM_OVERRIDE   = 0x02, // S31 -> C3: Force WHIM Connected / Paired status
    INTERCHIP_CMD_MEDIA_KEY       = 0x03, // S31 -> C3: USB HID Consumer Media Key Pulse
    INTERCHIP_CMD_VOLUME_SET      = 0x04, // S31 -> C3: Volume 0..100%
    INTERCHIP_CMD_MUX_SELECT      = 0x05, // S31 -> C3: Target Display (0=SkylineOS / Boom!, 1=Aftermarket AA)
    INTERCHIP_RESP_STATUS         = 0x10, // C3 -> S31: Connection Status & CarPlay Active Flag
    INTERCHIP_RESP_VOLUME_FEEDBACK= 0x11, // C3 -> S31: Headunit Volume Level Echo
    INTERCHIP_RESP_HEADUNIT_EVENT = 0x12  // C3 -> S31: Headunit physical buttons/wheel events
};

typedef struct __attribute__((packed)) {
    uint8_t  magic;          // INTERCHIP_MAGIC (0xA5)
    uint8_t  pkt_type;       // InterchipPktType
    uint8_t  payload_len;
    uint8_t  payload[32];
    uint16_t crc16;
} InterchipFrame;

// Media Key HID Codes
enum MediaKeyCode : uint8_t {
    MEDIA_KEY_PLAY_PAUSE = 0x01,
    MEDIA_KEY_NEXT_TRACK = 0x02,
    MEDIA_KEY_PREV_TRACK = 0x03,
    MEDIA_KEY_VOL_UP     = 0x04,
    MEDIA_KEY_VOL_DOWN   = 0x05,
    MEDIA_KEY_MUTE       = 0x06,
    MEDIA_KEY_SIRI_VOICE = 0x07
};

// Headunit Connection State
typedef struct {
    bool     usb_enumerated;
    bool     whim_emulation_active;
    bool     carplay_active;
    bool     speakers_active;
    uint8_t  headunit_vol_pct;
    uint8_t  current_mux_target; // 0=SkylineOS, 1=Aftermarket
} C3HeadunitState;
